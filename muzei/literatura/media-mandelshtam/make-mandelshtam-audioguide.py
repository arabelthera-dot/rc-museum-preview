#!/usr/bin/env python3
# Аудиогид «Мы живём, под собою не чуя страны» — Мандельштам, эпиграмма 1933 года и её судьба.
# Голос мужской, документальный комментарий (museum-literatura), не декламация.
# edge-tts рвётся на длинном тексте одним вызовом — синтез по абзацам, склейка байтов mp3.
import asyncio
import os

import edge_tts
from mutagen.mp3 import MP3 as MP3Info

OUT = os.path.dirname(os.path.abspath(__file__))
VOICE = "ru-RU-DmitryNeural"
RATE = "-6%"
MP3 = f"{OUT}/../audio-guide-mandelshtam-goretc-ru.mp3"

PARTS = [
    "Осип Мандельштам. «Мы живём, под собою не чуя страны». Ноябрь тысяча девятьсот тридцать третьего года.",
    "Мы живём, под собою не чуя страны. Наши речи за десять шагов не слышны. А где хватит на "
    "полразговорца, там припомнят кремлёвского горца. Его толстые пальцы, как черви, жирны, а слова, "
    "как пудовые гири, верны. Тараканьи смеются усища, и сияют его голенища. А вокруг него сброд "
    "тонкошеих вождей, он играет услугами полулюдей. Кто свистит, кто мяучит, кто хнычет, он один лишь "
    "бабачит и тычет. Как подкову, дарит за указом указ: кому в пах, кому в лоб, кому в бровь, кому в "
    "глаз. Что ни казнь у него — то малина, и широкая грудь осетина.",
    "Мандельштам читал эти строки знакомым сам, не скрывая авторства. По воспоминаниям его жены "
    "Надежды Яковлевны, стихи услышали около десяти человек из близкого круга. В ночь с тринадцатого "
    "на четырнадцатое мая тысяча девятьсот тридцать четвёртого года поэта арестовали; следователь на "
    "допросе назвал стихотворение террористическим актом.",
    "Прочитав стихи, Борис Пастернак сказал: то, что вы мне прочли, не имеет никакого отношения к "
    "литературе, поэзии. Это не литературный факт, но акт самоубийства, который я не одобряю и в "
    "котором не хочу принимать участия.",
    "Николай Бухарин взялся хлопотать за поэта, не зная, в чём его обвиняют. Как он потом рассказывал "
    "Илье Эренбургу, глава ОГПУ Генрих Ягода выучил стихи про Сталина наизусть и продекламировал их "
    "ему — Бухарин испугался и отступился.",
    "Сам Сталин позвонил Пастернаку. Пастернак ответил, что да, но что дело не в этом. А в чём? В "
    "том, что им нужно поговорить — о жизни и смерти. Сталин положил трубку.",
    "Мандельштама не расстреляли: его отправили в ссылку в Чердынь, а затем разрешили перебраться в "
    "Воронеж. Второй арест настиг поэта в мае тысяча девятьсот тридцать восьмого года; приговор — пять "
    "лет лагерей. Мандельштам умер двадцать седьмого декабря в лагере под Владивостоком. В официальном "
    "документе причиной смерти записано истощение — не тиф, как часто пишут.",
]


async def main():
    chunks = []
    for i, text in enumerate(PARTS):
        tmp = f"{OUT}/part-{i:02d}.mp3"
        for attempt in range(12):
            try:
                tts = edge_tts.Communicate(text, VOICE, rate=RATE)
                await tts.save(tmp)
                break
            except Exception as e:
                wait = min(60, 3 * (attempt + 1))
                print(f"part {i} attempt {attempt}: {e} -> sleep {wait}s")
                await asyncio.sleep(wait)
        else:
            raise RuntimeError(f"part {i} failed after retries")
        chunks.append(tmp)
        print(f"part {i}: {os.path.getsize(tmp)} bytes")

    cumulative = 0.0
    stops = []
    for i, c in enumerate(chunks):
        stops.append(round(cumulative, 2))
        cumulative += MP3Info(c).info.length
    print("stops (seconds):", stops)
    print("total duration:", round(cumulative, 2))

    with open(MP3, "wb") as out:
        for c in chunks:
            with open(c, "rb") as f:
                out.write(f.read())
    for c in chunks:
        os.remove(c)
    print(f"OK: {MP3} ({os.path.getsize(MP3)} bytes)")


if __name__ == "__main__":
    asyncio.run(main())
