#!/usr/bin/env python3
# Аудиогид «Умом Россию не понять» — Тютчев, четверостишие 1866 года плюс его судьба.
# Голос мужской, читается как документальный комментарий, а не декламация (museum-literatura).
# edge-tts рвётся на длинном тексте одним вызовом — синтез по абзацам, склейка байтов mp3.
import asyncio
import os

import edge_tts

OUT = os.path.dirname(os.path.abspath(__file__))
VOICE = "ru-RU-DmitryNeural"
RATE = "-6%"
MP3 = f"{OUT}/../audio-guide-umom-rossiyu-tyutchev-ru.mp3"

PARTS = [
    "Фёдор Тютчев. «Умом Россию не понять». Тысяча восемьсот шестьдесят шестой год.",
    "Умом Россию не понять, аршином общим не измерить: у ней особенная стать — в Россию можно только верить.",
    "Тютчев набросал эти четыре строки карандашом на обрезанном листке бумаги, двадцать восьмого ноября "
    "тысяча восемьсот шестьдесят шестого года. В конце четверостишия он не поставил точку, а во второй "
    "строке — тире вместо неё.",
    "Напечатали стихи только через два года, в тысяча восемьсот шестьдесят восьмом, в сборнике "
    "стихотворений Тютчева.",
    "Литературовед Вадим Кожинов спорил с привычным прочтением этих строк. Тютчев, по его мнению, "
    "говорил не о загадочной непостижимости русских, а о том, что Россия держится верой тех, кто в ней живёт.",
    "Через четыре десятилетия строку произносили уже как упрёк. Максим Горький в тысяча девятьсот пятом "
    "году писал в газете «Новая жизнь»: в эти дни, когда рыцари бились насмерть со змеем, мещанство в "
    "стихах и прозе доказывало, что умом Россию не понять.",
    "Строку повторяли и главы государств. Жак Ширак прочитал её, получая Государственную премию России. "
    "А Владимир Путин произнёс её перед президентом Франции Николя Саркози — заменив «можно только верить» "
    "на «нужно просто верить».",
]


async def main():
    chunks = []
    for i, text in enumerate(PARTS):
        tmp = f"{OUT}/part-{i:02d}.mp3"
        for attempt in range(12):
            try:
                tts = edge_tts.Communicate(text, VOICE, rate=RATE)
                await tts.save(tmp)
                break
            except Exception as e:
                wait = min(60, 3 * (attempt + 1))
                print(f"part {i} attempt {attempt}: {e} -> sleep {wait}s")
                await asyncio.sleep(wait)
        else:
            raise RuntimeError(f"part {i} failed after retries")
        chunks.append(tmp)
        print(f"part {i}: {os.path.getsize(tmp)} bytes")

    with open(MP3, "wb") as out:
        for c in chunks:
            with open(c, "rb") as f:
                out.write(f.read())
    for c in chunks:
        os.remove(c)
    print(f"OK: {MP3} ({os.path.getsize(MP3)} bytes)")


if __name__ == "__main__":
    asyncio.run(main())
